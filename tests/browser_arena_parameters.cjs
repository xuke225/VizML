/* End-to-end proof: native lab options -> Arena controls -> real fitted estimator. */
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {chromium} = require('playwright');
const output = path.resolve('.arena-qa');
fs.mkdirSync(output,{recursive:true});
(async()=>{
    const browser=await chromium.launch({headless:true,executablePath:process.env.ARENA_BROWSER_EXE ||
        'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const snap=()=>page.evaluate(()=>window.VizMLArena.snapshot());
    const open=async key=>{
        const panel=page.locator('[data-parameter-model='+key+']');
        if(!await panel.evaluate(e=>e.open))await panel.locator('summary').click();
    };
    const fill=async(id,value)=>{await page.locator('#arena-'+id).fill(value);await page.locator('#arena-'+id).press('Tab');};
    const select=async(id,value)=>page.locator('#arena-'+id).selectOption(value);
    let holdout;
    const run=async()=>{
        const reply=page.waitForResponse(r=>r.url().endsWith('/api/arena/run')&&r.request().method()==='POST');
        await page.locator('#arena-run').click();
        const result=await (await reply).json();
        assert.equal(result.status,'success',result.message);
        await page.waitForFunction(()=>{const s=window.VizMLArena.snapshot();return s.fresh&&!s.busy&&s.revealProgress===1;});
        assert.equal(Object.keys(result.models).length,6);
        if(holdout)assert.equal(result.holdout_fingerprint,holdout);
        holdout=result.holdout_fingerprint;
        return result;
    };
    try {
        await page.goto((process.env.ARENA_URL||'http://localhost:5432')+'/#ml-arena');
        await page.waitForFunction(()=>window.VizMLArena?.snapshot().split);
        await page.locator('#arena-data-expand').click();
        assert.equal(await page.locator('.arena-param-field').count(),35);
        assert.equal(await page.locator('.arena-model canvas').count(),6);
        assert.deepEqual(await page.locator('#arena-kernel option').evaluateAll(es=>es.map(e=>e.value)),['linear','rbf','poly','sigmoid']);
        await select('kernel','poly');
        assert.ok(await page.locator('#arena-svm-degree').isVisible());
        await fill('svm-degree','4');await fill('svm-coef0','1.1');
        await fill('c','2');await fill('gamma-custom','0.4');
        await fill('svm-iterations','1800');await fill('svm-tol','0.002');
        await page.locator('#arena-svm-scale').uncheck();
        let r=await run(),m=r.models.svm;
        for(const [key,value] of Object.entries({kernel:'poly',degree:4,coef0:1.1,C:2,gamma:.4,max_iter:1800,tol:.002}))
            assert.equal(m.effective_params[key],value,key);
        assert.equal(m.preprocessing.standardize,false);
        const effective=page.locator('[data-model=svm] .arena-effective-params');
        await effective.locator('summary').click();
        assert.match(await page.locator('#arena-effective-svm').textContent(),/"degree": 4/);
        await open('svm');await select('kernel','sigmoid');
        assert.ok(await page.locator('#arena-svm-degree').isHidden());
        r=await run();assert.equal(r.models.svm.effective_params.kernel,'sigmoid');
        await open('svm');await select('kernel','rbf');await select('gamma','auto');
        assert.ok(await page.locator('#arena-gamma-custom').isHidden());
        r=await run();assert.equal(r.models.svm.effective_params.gamma,'auto');
        await open('svm');await select('gamma','scale');await page.locator('#arena-svm-scale').check();
        r=await run();assert.equal(r.models.svm.effective_params.gamma,'scale');
        assert.ok(Math.abs(r.models.svm.fit_info.effective_gamma-.5)<1e-8);
        await open('svm');await select('kernel','linear');
        assert.ok(await page.locator('#arena-gamma').isHidden());
        r=await run();assert.equal(r.models.svm.effective_params.kernel,'linear');
        console.log('PASS SVM: all four kernels, numeric/auto/scale gamma, degree/coef0, C, max_iter/tol, scaling and actual parameter inspector');
        await open('knn');await select('knn-metric','minkowski');await fill('knn-p','1.5');
        await select('weights','distance');await page.locator('#arena-knn-scale').uncheck();
        r=await run();assert.equal(r.models.knn.effective_params.metric,'minkowski');
        assert.equal(r.models.knn.effective_params.p,1.5);assert.equal(r.models.knn.preprocessing.standardize,false);
        await open('tree');await select('tree-criterion','entropy');await select('tree-features','log2');
        await fill('depth','');await fill('tree-split','7');await fill('leaf','3');await page.locator('#arena-tree-scale').check();
        r=await run();m=r.models.tree;
        assert.equal(m.effective_params.max_depth,null);assert.equal(m.effective_params.criterion,'entropy');
        assert.equal(m.effective_params.min_samples_split,7);assert.equal(m.effective_params.min_samples_leaf,3);
        assert.equal(m.effective_params.max_features,'log2');assert.equal(m.preprocessing.standardize,true);
        await open('forest');await fill('forest-trees','8');await fill('forest-depth','20');
        await fill('forest-split','5');await fill('forest-leaf','2');await select('forest-features','auto');
        r=await run();m=r.models.forest;
        assert.equal(m.effective_params.n_estimators,8);assert.equal(m.effective_params.max_depth,20);
        assert.equal(m.effective_params.min_samples_split,5);assert.equal(m.effective_params.min_samples_leaf,2);
        assert.equal(m.configured_params.max_features,'auto');assert.equal(m.effective_params.max_features,'sqrt');
        console.log('PASS KNN/tree/forest: distance and p, scaling, entropy, all split/leaf/features controls, unlimited depth, transparent auto compatibility');
        await open('mlp');await select('mlp-hidden','100,100,100,100,50');
        await select('mlp-activation','tanh');await select('mlp-solver','sgd');
        await fill('mlp-rate','0.01');await fill('mlp-iterations','100');await fill('mlp-alpha','0.01');await fill('mlp-batch','12');
        r=await run();m=r.models.mlp;
        assert.deepEqual(m.fit_info.network,[2,100,100,100,100,50,1]);
        assert.equal(m.effective_params.solver,'sgd');assert.equal(m.effective_params.activation,'tanh');
        assert.equal(m.effective_params.learning_rate_init,.01);assert.equal(m.effective_params.batch_size,12);
        await open('mlp');await select('mlp-hidden','custom');await fill('mlp-hidden-custom','8,4');
        await select('mlp-solver','lbfgs');
        assert.ok(await page.locator('#arena-mlp-rate').isHidden());
        assert.ok(await page.locator('#arena-mlp-batch').isHidden());
        r=await run();assert.deepEqual(r.models.mlp.fit_info.network,[2,8,4,1]);
        assert.equal(r.models.mlp.fit_info.solver,'lbfgs');assert.deepEqual(r.models.mlp.fit_info.loss_curve,[]);
        await open('mlp');await select('mlp-type','perceptron');await fill('mlp-rate','0.015');
        assert.ok(await page.locator('#arena-mlp-hidden').isHidden());
        r=await run();m=r.models.mlp;
        assert.equal(m.effective_params.eta0,.015);assert.equal(m.fit_info.network_type,'perceptron');
        assert.ok(Object.values(m.explanations).every(e=>'decision_score'in e&&!('probabilities'in e)));
        assert.equal(await page.locator('[data-model=mlp] header strong').textContent(),'PERCEPTRON');
        console.log('PASS neural network: five-layer preset, custom architecture, Tanh, SGD learning rate/batch, L-BFGS without fake loss curve, perceptron without fake probabilities');
        await open('bayes');await select('bayes-priors','custom');await fill('bayes-priors-custom','0.8,0.2');
        await fill('bayes-smoothing','3.1622776601683795e-9');await page.locator('#arena-bayes-scale').check();
        r=await run();assert.deepEqual(r.models.bayes.effective_params.priors,[.8,.2]);
        assert.equal(r.models.bayes.effective_params.var_smoothing,3.1622776601683795e-9);
        assert.equal(r.models.bayes.preprocessing.standardize,true);
        console.log('PASS Bayes: arbitrary smoothing values, custom priors, train-only scaling');
        await open('svm');await select('kernel','poly');
        await page.addStyleTag({content:'.site-header,.skip-link{visibility:hidden!important}'});
        await page.locator('.arena-studio').screenshot({path:path.join(output,'parameters-complete.png')});
        assert.deepEqual(errors,[]);
        console.log('ALL COMPLETE PARAMETER BROWSER CHECKS PASSED');
    } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
