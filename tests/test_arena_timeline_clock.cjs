const assert=require('node:assert/strict');
const Clock=require('../frontend/static/js/arena-timeline-clock.js');
const tracks={fast:{duration_ms:4,frames:[{elapsed_ms:1},{elapsed_ms:2},{elapsed_ms:4}]},
    slow:{duration_ms:10,frames:[{elapsed_ms:3},{elapsed_ms:10}]}};
const clock=new Clock(tracks,0.001);
clock.play(100);
clock.tick(2100);
assert.equal(clock.time,2);
assert.deepEqual(clock.positions(),{fast:1,slow:-1});
clock.pause(3100);
assert.equal(clock.time,3);
clock.tick(100000);
assert.equal(clock.time,3,'pause must freeze measured time');
clock.setSpeed(0.01,100000);
assert.equal(clock.time,3,'changing speed while paused cannot jump');
clock.play(100000);clock.tick(100100);
assert.equal(clock.time,4);
assert.deepEqual(clock.positions(),{fast:2,slow:0});
clock.setSpeed(0.1,100150);
assert.equal(clock.time,4.5,'elapsed segment must use OLD speed');
clock.tick(100155);
assert.equal(clock.time,5,'new speed applies immediately to remaining time');
clock.pause(100155);clock.seek(1.5,100200);
assert.deepEqual(clock.positions(),{fast:0,slow:-1});
assert.equal(clock.playing,false);
clock.seek(999,100200);
assert.equal(clock.time,10);
assert.equal(clock.playing,false);
clock.seek(0,100201);clock.play(100201);clock.tick(200000);
assert.equal(clock.playing,false);
assert.equal(clock.time,10);
for(const invalid of [0,-1,NaN,Infinity,11,0.000001])assert.throws(()=>clock.setSpeed(invalid,200000),RangeError);
console.log('PASS measured-time clock: independent tracks, pause/resume, live speed, seek, end, invalid speeds');
