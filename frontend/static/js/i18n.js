    /* 模板：中文模板 → 英文模板（{0} {1} 为占位符） */
    var templates = {
        '当前显示{0}的 {1} 个算法实验': 'Showing {0} · {1} labs'
    };

    /* ============ 引擎 ============ */
    var currentLang = 'zh';
    var snapshot = new Map(); /* 节点 → 原文（用于切回中文时恢复） */

    try {
        currentLang = localStorage.getItem(STORAGE_KEY) || 'zh';
        if (currentLang !== 'zh' && currentLang !== 'en') currentLang = 'zh';
    } catch (e) { /* localStorage 不可用时保持 zh */ }

    function t(key) {
        if (currentLang === 'en') return dict[key] || key;
        return key;
    }

    function tpl(template, params) {
        var text = currentLang === 'en' ? (templates[template] || template) : template;
        return text.replace(/\{(\d+)\}/g, function (m, i) {
            return params && params[i] !== undefined ? String(params[i]) : m;
        });
    }

    function hasChinese(str) {
        return /[\u4e00-\u9fff]/.test(str);
    }

    function translateSentence(text) {
        if (!hasChinese(text)) return null;
        if (dict[text]) return dict[text];
        /* 分句匹配：按中英文句末标点切分后逐句替换 */
        var parts = text.split(/([。！？；!?;])/);
        var changed = false;
        var out = parts.map(function (seg, idx) {
            if (idx % 2 === 1) return seg; /* 分隔符原样保留 */
            var trimmed = seg.trim();
            if (trimmed && dict[trimmed]) {
                changed = true;
                return dict[trimmed];
            }
            return seg;
        });
        return changed ? out.join('') : null;
    }

    function apply() {
        var root = document.body;
        if (!root) return;

        /* 1. 恢复上一轮快照（切回中文或重新应用前） */
        restoreSnapshot();

        if (currentLang === 'zh') {
            document.documentElement.lang = 'zh-CN';
            updateTitle();
            updateToggleButton();
            return;
        }

        document.documentElement.lang = 'en';

        /* 2. 文本节点翻译 */
        var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: function (node) {
                var parent = node.parentNode;
                if (!parent) return NodeFilter.FILTER_REJECT;
                var tag = parent.nodeName;
                if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT' ||
                    tag === 'TEXTAREA' || tag === 'SVG' || tag === 'TEMPLATE') {
                    return NodeFilter.FILTER_REJECT;
                }
                return NodeFilter.FILTER_ACCEPT;
            }
        });
        var textNodes = [];
        while (walker.nextNode()) textNodes.push(walker.currentNode);

        textNodes.forEach(function (node) {
            var original = node.nodeValue;
            if (!original || !hasChinese(original)) return;
            var translation = translateSentence(original);
            if (translation !== null && translation !== original) {
                snapshot.set(node, original);
                node.nodeValue = translation;
            }
        });

        /* 3. 关键属性翻译（aria-label / title / placeholder / alt） */
        var elements = root.querySelectorAll('*');
        elements.forEach(function (el) {
            TEXT_ATTRS.forEach(function (attr) {
                var value = el.getAttribute(attr);
                if (!value || !hasChinese(value)) return;
                var translation = translateSentence(value);
                if (translation !== null && translation !== value) {
                    snapshot.set(el, { attr: attr, value: value });
                    el.setAttribute(attr, translation);
                }
            });
        });

        updateTitle();
        updateToggleButton();
    }

    function restoreSnapshot() {
        snapshot.forEach(function (stored, node) {
            try {
                if (typeof stored === 'string') {
                    node.nodeValue = stored;
                } else if (stored && stored.attr) {
                    node.setAttribute(stored.attr, stored.value);
                }
            } catch (e) { /* 节点已失效则忽略 */ }
        });
        snapshot = new Map();
    }

    function updateTitle() {
        var original = 'VizML · 让机器学习算法看得见';
        if (document.title === original || dict[document.title]) {
            document.title = t(original);
        }
    }

    /* ============ 切换按钮 ============ */
    function updateToggleButton() {
        var btn = document.getElementById('vizml-lang-toggle');
        if (!btn) return;
        var isZh = currentLang === 'zh';
        btn.textContent = isZh ? 'EN' : '中文';
        btn.setAttribute('aria-label', t('切换语言'));
        btn.setAttribute('title', t('切换语言'));
        btn.setAttribute('lang', isZh ? 'en' : 'zh-CN');
    }

    function ensureToggleButton() {
        if (document.getElementById('vizml-lang-toggle')) return;
        var btn = document.createElement('button');
        btn.type = 'button';
        btn.id = 'vizml-lang-toggle';
        btn.className = 'vizml-lang-toggle';
        btn.addEventListener('click', function () {
            currentLang = currentLang === 'zh' ? 'en' : 'zh';
            try { localStorage.setItem(STORAGE_KEY, currentLang); } catch (e) { /* ignore */ }
            apply();
            window.dispatchEvent(new CustomEvent('vizml:langchange', { detail: { lang: currentLang } }));
        });
        document.body.appendChild(btn);
        updateToggleButton();
    }

    /* ============ 对外 API ============ */
    window.VizMLI18n = {
        t: t,
        tpl: tpl,
        getLang: function () { return currentLang; }
    };

    /* ============ 初始化（兼容 head 同步加载与 defer 两种方式） ============ */
    function init() {
        ensureToggleButton();
        apply();
    }
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
